const riskDetection = `安全隐患检测采用两阶段 AI 检测流水线，确保高精度和高召回率：

**Phase 1 — 场景识别**
1. 在「隐患识别」页面点击上传图片
2. VLM 视觉大模型分析图片内容
3. 识别是否为消防控制柜场景
4. 非机柜场景直接返回通用安全检测结果

**Phase 2 — 精准比对**（识别到 4 种消防控制柜时触发）
1. **优先 CV 检测**：ORB 特征提取 → FLANN LSH 匹配 → RANSAC 单应矩阵验证 → LAB L 通道灯位亮灭分析（阈值 145）
2. **VLM 降级**：CV 匹配失败时，将用户图与标准参考图发 VLM 做视觉对比

**检测输出**
- 灯位状态列表（亮/灭/异常）
- 与标准配置的差异比对
- Markdown + Word 双格式检测报告
- 支持历史记录回溯

**注意事项**
- 图片大小超过 300KB 会自动压缩
- 上传前请确保图片清晰、角度正对机柜面板
- 支持批量上传检测`;

