def classify(details: dict, keywords: dict | None = None) -> dict:
  """对所附详情的原文**按单归类**（确定性，每张单只投 1 票）。

  返回 `{类别: 单数, ..., '可归类': x, '未归入': y}`。此前是**关键词命中次数**计数，
  模型把它当单数写（实测：本期共 11 单，正文写成"业务容量变化类调整共 23 单"）——
  次数与单数不是一回事，必须按单。

  **扫全部字段值**（不只原因分析/处理结果）：故障单的 `处置过程/故障描述` 里才有成
  因证据，写死事件字段名会让故障报告的成因永远为空。
  关键词表按工单类型传入（变更单的成因是「为什么要动」，不是故障的失效模式）。
  """
  table = keywords or CAUSE_KEYWORDS
  counts = {label: 0 for label in table}
  classified = unclassified = 0
  for it in (details or {}).get('rows', []):
    text = ' '.join(v for v in (it.get('fields') or {}).values() if isinstance(v, str))
    hit = next((label for label, kws in table.items()
                if any(k in text for k in kws)), '')
    if hit:
      counts[hit] += 1
      classified += 1
    else:
      unclassified += 1
  out = {label: n for label, n in counts.items() if n}
  out['可归类'] = classified
  out['未归入'] = unclassified
  return out
