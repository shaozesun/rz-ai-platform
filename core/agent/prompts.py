# 「即将上线」里的 DCIM 行：**按开关渲染**，别写死。DCIM 接入后打开 DCIM_ENABLED，
# 这行自动消失——否则能力清单会第二次变成过期副本（这正是本次要修的病根）。
_DCIM_PENDING_LINE = (
  '- DCIM 数据中心实时数据（实时告警、告警历史、设备资产、容量、用电）\n'
)


def _dcim_pending() -> str:
  """DCIM 未启用时返回「即将上线」那一行，启用后返回空串。"""
  from config.settings import settings
  return '' if settings.DCIM_ENABLED else _DCIM_PENDING_LINE


def system_prompt(user_name: str) -> str:
  """渲染 SYSTEM_PROMPT（**唯一**该用它的地方，别在别处直接 .format）。

  为什么包一层：提示词里有大量 JSON/占位示例，**任何没转义的 `{`** 都会让 `str.format`
  抛 KeyError——实测事故：新增的一条规则里写了 `{"error": …}` → `KeyError: '"error"'`，
  建 agent 当场失败、**整个对话全挂**（而且这类错 pyflakes 查不出来）。这里把报错换成
  一眼能看懂的说明，并写明修法：字面量花括号要写成 `{{ }}`。
  """
  try:
    return SYSTEM_PROMPT.format(**{
      'user_name': user_name,
      'dcim_pending': _dcim_pending(),
    })
  except (KeyError, IndexError, ValueError) as e:
    raise RuntimeError(
      f'SYSTEM_PROMPT 渲染失败：有未转义的花括号（{e}）。提示词里的字面量花括号必须写成 '
      f'{{{{ }}}}（如 JSON 示例 {{"a": 1}} 要写成 {{{{"a": 1}}}}）'
    ) from e


def verify_prompts() -> None:
  """启动自检：会被 `.format()` 的提示词先干跑一遍，别等线上请求时才炸。

  这点开销（毫秒级）换的是"整个对话不可用"这类事故提前暴露在启动阶段。
  """
  system_prompt('自检')
  for name in ('PLAN_MODE_INSTRUCTION',):
    text = globals().get(name)
    if isinstance(text, str):
      try:
        text.format()
      except (KeyError, IndexError, ValueError) as e:
        raise RuntimeError(f'{name} 里有未转义的花括号（{e}）：字面量要写成 {{{{ }}}}') from e
